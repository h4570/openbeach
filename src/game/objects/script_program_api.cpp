const std::vector<NamedId>& EngineFunctions()
{
    static const std::vector<NamedId> kTable = Table(kFunctions);
    return kTable;
}

const std::vector<NamedId>& EngineValues()
{
    static const std::vector<NamedId> kTable = Table(kValues);
    return kTable;
}

