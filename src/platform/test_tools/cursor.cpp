// The callers are the DLL's own code and the SDL linked into it.
bool RegisterCursorTrace()
{
    return platform::RedirectImport("user32.dll", "ClipCursor", &TracedClipCursor, &g_ClipCursor) &&
            platform::RedirectImport("user32.dll", "SetCursorPos", &TracedSetCursorPos, &g_SetCursorPos) &&
            platform::RedirectImport("user32.dll", "ShowCursor", &TracedShowCursor, &g_ShowCursor) &&
            platform::RedirectImport("user32.dll", "SetSystemCursor", &TracedSetSystemCursor, &g_SetSystemCursor) &&
            platform::RedirectImport("user32.dll", "SetCursor", &TracedSetCursor, &g_SetCursor);
}

bool ExecuteCursorCommand(const std::string& name)
{
    if (name == "sdl-relative-drag-contract") {
        CheckSdlRelativeDrag();
        return true;
    }
    if (name != "cursor-contract") return false;
    CheckCursor();
    return true;
}

